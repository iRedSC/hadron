package dev.iredsc.hadron.regions;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import dev.iredsc.hadron.api.event.Cancellable;
import dev.iredsc.hadron.api.event.Event;
import dev.iredsc.hadron.api.event.block.BlockBreakEvent;
import java.io.IOException;
import java.lang.reflect.Modifier;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystem;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * The table from events to nodes covers every event that can be refused, every node is reached, and the node table in
 * the README is the one the code makes.
 */
class NodeMappingTest {
    private final Nodes nodes = new Nodes();

    @Test
    void everyCancellableEventInApiHasAnEntryOfItsOwn() throws Exception {
        List<String> missing = missing(nodes.mapping().keySet(), eventClasses());
        if (!missing.isEmpty()) fail(String.join("\n", missing));
    }

    /** The check above can fail: with one entry taken out, it names that event and the fix. */
    @Test
    void anEventWhoseEntryIsRemovedIsNamed() throws Exception {
        Set<Class<? extends Event>> without = new HashSet<>(nodes.mapping().keySet());
        without.remove(BlockBreakEvent.class);
        assertEquals(List.of("BlockBreakEvent has no region node: add it to Nodes as the node it is, or "
                + "notRegions(\"why no region decides it\")"), missing(without, eventClasses()));
    }

    @Test
    void everyNodeIsProducedByAnEntry() {
        Set<Action> produced = EnumSet.noneOf(Action.class);
        for (Nodes.Entry e : nodes.mapping().values()) {
            if (e instanceof Nodes.Entry.Asking a) produced.addAll(a.produces());
        }
        List<String> dead = new ArrayList<>();
        for (Action a : Action.values()) {
            if (!produced.contains(a)) dead.add(a.key() + " is produced by no event: map an event to it, or remove it");
        }
        if (!dead.isEmpty()) fail(String.join("\n", dead));
    }

    @Test
    void nodeKeysAreUniqueLowercaseAndNeverASubjectOrFlag() {
        Set<String> seen = new HashSet<>();
        for (Node n : Node.all()) {
            assertTrue(seen.add(n.key()), n.key() + " is two nodes");
            assertTrue(n.key().matches("[a-z]+(\\.[a-z]+)*"), n.key() + " should be lowercase segments");
            assertTrue(Bundle.named(n.key()).isEmpty(), n.key() + " is also a flag's name");
            for (Subject s : Subject.values()) assertTrue(!n.key().equals(s.key()), n.key() + " is also a subject");
        }
    }

    @Test
    @SuppressWarnings("NullAway") // the classes are only looked up, never made
    void aBridgesOwnSubclassFallsBackToItsParentAndAnUnmappedActionToOther() {
        abstract class ModsBreak extends BlockBreakEvent {
            ModsBreak() {
                super(null, (dev.iredsc.hadron.api.event.block.BlockChange) null, null);
            }
        }
        assertEquals(nodes.mapping().get(BlockBreakEvent.class), nodes.entryFor(ModsBreak.class));
        abstract class ModsOwnAction extends dev.iredsc.hadron.api.event.ActionEvent implements Cancellable {
            ModsOwnAction() {
                super(null);
            }
        }
        Nodes.Entry other = nodes.entryFor(ModsOwnAction.class);
        assertTrue(other instanceof Nodes.Entry.Asking a && a.produces().equals(Set.of(Action.OTHER)),
                "an action nothing maps should be asked as other, which fails closed, but was " + other);
    }

    @Test
    void theReadmesNodeTableIsTheOneTheCodeMakes() throws IOException {
        Path readme = Path.of("README.md");
        String text = Files.readString(readme, StandardCharsets.UTF_8);
        int start = text.indexOf(START);
        int end = text.indexOf(END);
        assertTrue(start >= 0 && end > start, "README.md should hold the node table between " + START + " and " + END);
        String expected = text.substring(0, start + START.length()) + "\n" + table(nodes) + text.substring(end);
        if (expected.equals(text)) return;
        if (Boolean.getBoolean("regions.nodeTable.write")) {
            Files.writeString(readme, expected, StandardCharsets.UTF_8);
            return;
        }
        fail("plugins/regions/README.md's node table is stale: run ./gradlew :plugins:regions:nodeTable to rewrite it");
    }

    static final String START = "<!-- node table: generated by NodeMappingTest; ./gradlew :plugins:regions:nodeTable -->";
    static final String END = "<!-- end of node table -->";

    /** The README's node table: each action with its flag per kind and the events asking it, then what isn't a region's. */
    static String table(Nodes nodes) {
        Map<Action, TreeSet<String>> asking = new LinkedHashMap<>();
        Map<String, String> notRegions = new TreeMap<>();
        for (Map.Entry<Class<? extends Event>, Nodes.Entry> e : nodes.mapping().entrySet()) {
            String name = e.getKey().getSimpleName();
            switch (e.getValue()) {
                case Nodes.Entry.Asking a -> {
                    for (Action action : a.produces()) asking.computeIfAbsent(action, x -> new TreeSet<>()).add(name);
                }
                case Nodes.Entry.NotRegions n -> notRegions.put(name, n.reason());
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("| node | flag | meaning | asked by |\n|---|---|---|---|\n");
        for (Action a : Action.values()) {
            String flag;
            if (!a.kinded()) {
                flag = a.bundle(Kind.MISC).key();
            } else {
                List<String> per = new ArrayList<>();
                for (Kind k : Kind.values()) per.add(k.key() + ": " + a.bundle(k).key());
                flag = String.join(", ", per);
            }
            out.append("| `").append(a.key()).append(a.kinded() ? ".<kind>" : "").append("` | ").append(flag)
                    .append(" | ").append(a.meaning()).append(" | ")
                    .append(String.join(", ", asking.getOrDefault(a, new TreeSet<>()))).append(" |\n");
        }
        out.append("\nNot a region's:\n\n| event | why |\n|---|---|\n");
        for (Map.Entry<String, String> e : notRegions.entrySet()) {
            out.append("| ").append(e.getKey()).append(" | ").append(e.getValue()).append(" |\n");
        }
        return out.toString();
    }

    /**
     * Each event class that is cancellable, or has a cancellable subclass among {@code classes}, and has no entry of
     * its own in {@code mapped}: an inherited entry doesn't count, so a new core event is never lumped in with its
     * parent.
     */
    static List<String> missing(Set<Class<? extends Event>> mapped, List<Class<?>> classes) {
        List<String> out = new ArrayList<>();
        for (Class<?> c : classes) {
            if (c == Event.class || !Event.class.isAssignableFrom(c) || mapped.contains(c)) continue;
            boolean refusable = false;
            for (Class<?> d : classes) {
                if (c.isAssignableFrom(d) && Cancellable.class.isAssignableFrom(d)) refusable = true;
            }
            if (refusable) {
                out.add(c.getSimpleName() + " has no region node: add it to Nodes as the node it is, or "
                        + "notRegions(\"why no region decides it\")");
            }
        }
        return out;
    }

    /** Every public class in {@code api}, from its classes directory or its jar. */
    static List<Class<?>> eventClasses() throws Exception {
        Path root = Path.of(Event.class.getProtectionDomain().getCodeSource().getLocation().toURI());
        List<String> names = new ArrayList<>();
        if (Files.isDirectory(root)) {
            names.addAll(classNames(root));
        } else {
            try (FileSystem jar = FileSystems.newFileSystem(URI.create("jar:" + root.toUri()), Map.of())) {
                names.addAll(classNames(jar.getPath("/")));
            }
        }
        List<Class<?>> out = new ArrayList<>();
        for (String name : names) {
            if (!name.startsWith("dev.iredsc.hadron.api.")) continue;
            Class<?> c = Class.forName(name, false, NodeMappingTest.class.getClassLoader());
            if (Modifier.isPublic(c.getModifiers()) && !c.isInterface()) out.add(c);
        }
        assertTrue(out.size() > 100, "should find api's events, but found " + out.size() + " classes in " + root);
        return out;
    }

    private static List<String> classNames(Path root) throws IOException {
        try (Stream<Path> files = Files.walk(root)) {
            return files.map(root::relativize).map(Path::toString).filter(f -> f.endsWith(".class"))
                    .map(f -> f.substring(0, f.length() - ".class".length()).replace('/', '.')).toList();
        }
    }
}
